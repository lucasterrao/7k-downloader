test('validação restringe URLs e opções; seleção de formato preserva o link como argumento', () => {
  assert.throws(() => validateRequest({ urls: ['file:///C:/secret'] }));
  assert.throws(() => validateRequest({ urls: ['https://user:pass@example.com/'] }));
  assert.throws(() => validateRequest({ urls: ['https://example.com'], format: '--exec' }));
  assert.throws(() => validateRequest({ urls: ['https://example.com'], quality: '1;calc' }));
  const options = validateRequest({ urls: ['https://example.com/?x=%26calc'], mode: 'audio', format: 'mp3', bitrate: '320' });
  const args = buildArgs({ options, url: options.urls[0] }, 'C:\\bin', 'C:\\downloads');
  assert.equal(args.at(-2), '--'); assert.equal(args.at(-1), options.urls[0]);
  assert.ok(args.includes('320K')); assert.ok(args.includes('--ignore-config'));
  assert.ok(args.includes('%(id)s/%(title).150B.%(ext)s'));
  assert.equal(youtubeVideoId('https://www.youtube.com/watch?v=2vySRN3VQDs'), '2vySRN3VQDs');
  assert.equal(youtubeVideoId('https://youtube.com.evil.example/watch?v=2vySRN3VQDs'), null);
});

test('API, fila, consulta, falha, cancelamento e persistência', async t => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), '7k-test-'));
  const engine = { file: process.execPath, prefix: [fileURLToPath(new URL('./fake-engine.mjs', import.meta.url))] };
  const app = await createApp({ root, engine, testing: true, noOpen: true });
  const address = new URL(await app.listen()); const origin = address.origin;
  const headers = { 'x-7k-token': app.token, 'Content-Type': 'application/json' };
  t.after(async () => { await app.close(); });
  const request = async (route, body) => { const r = await fetch(origin + '/api/' + route, { method: body === undefined ? 'GET' : 'POST', headers, body: body === undefined ? undefined : JSON.stringify(body) }); return { status: r.status, data: await r.json() }; };
  async function until(predicate) { for (let i = 0; i < 100; i++) { const state = (await request('status')).data; if (predicate(state)) return state; await new Promise(r => setTimeout(r, 40)); } throw new Error('Tempo de teste excedido.'); }
  assert.equal((await fetch(origin + '/api/status')).status, 403);
  assert.equal((await fetch(origin + '/api/status', { headers: { ...headers, Origin: 'https://outside.example' } })).status, 403);
  const wrongHostStatus = await new Promise((resolve, reject) => { const r = http.request(origin + '/api/status', { headers: { ...headers, Host: 'evil.example' } }, response => { response.resume(); resolve(response.statusCode); }); r.on('error', reject); r.end(); });
  assert.equal(wrongHostStatus, 403);
  assert.equal((await request('jobs', { urls: ['javascript:alert(1)'] })).status, 400);
  const preview = await request('preview', { urls: ['https://example.com/video'] }); assert.equal(preview.data.title, 'Vídeo de teste');
  const created = await request('jobs', { urls: ['https://example.com/slow1', 'https://example.com/slow2', 'https://example.com/normal'] });
  assert.equal(created.status, 201);
  let state = await until(s => s.jobs.filter(j => j.status === 'running' && j.title).length === 2);
  assert.equal(state.jobs.filter(j => j.status === 'queued').length, 1);
  for (const id of created.data.ids.slice(0, 2)) assert.equal((await request(`jobs/${id}/cancel`, {})).status, 200);
  state = await until(s => s.jobs.find(j => j.id === created.data.ids[2]).status === 'completed');
  const completed = state.jobs.find(j => j.status === 'completed'); assert.equal(completed.progress, 100); assert.equal(completed.files.length, 1); assert.equal(completed.title, 'Vídeo de teste');
  assert.equal(path.dirname(completed.files[0]),app.destination);assert.equal((await fs.readdir(app.destination,{withFileTypes:true})).filter(e=>e.isDirectory()).length,0);
  assert.equal(state.jobs.filter(j => j.status === 'canceled').length, 2);
  const failed = await request('jobs', { urls: ['https://example.com/fail'] });
  state = await until(s => s.jobs.find(j => j.id === failed.data.ids[0]).status === 'failed');
  assert.match(state.jobs.at(-1).message, /falha de teste/);
  assert.equal((await request(`jobs/${failed.data.ids[0]}/retry`, {})).status, 200);
  await until(s => s.jobs.find(j => j.id === failed.data.ids[0]).status === 'failed');
  const authJob = await request('jobs', { urls: ['https://example.com/needs-session'] });
  state = await until(s => s.jobs.find(j => j.id === authJob.data.ids[0]).status === 'failed' && s.jobs.find(j => j.id === authJob.data.ids[0]).titleSource === 'metadata');
  const blocked = state.jobs.find(j => j.id === authJob.data.ids[0]);
  assert.equal(blocked.title, 'Vídeo de teste'); assert.equal(blocked.requiresAuth, true); assert.match(blocked.message, /Preferências/);
  const invalid = path.join(root, 'invalid.txt'); await fs.writeFile(invalid, 'not a cookie file');
  assert.equal((await request('settings', { cookiesFile: invalid })).status, 400);
  assert.equal((await request('settings', { cookiesFile: '../relative.txt' })).status, 400);
  const cookieFile = path.join(root, 'cookies.txt'); await fs.writeFile(cookieFile, '# Netscape HTTP Cookie File\n.example.com\tTRUE\t/\tFALSE\t0\tsession\tDUMMY_TEST_VALUE\n');
  assert.equal((await request('settings', { cookiesFile: cookieFile })).status, 200);
  assert.equal((await request('settings')).data.cookiesFile, cookieFile);
  assert.equal((await request(`jobs/${blocked.id}/retry`, {})).status, 200);
  state = await until(s => s.jobs.find(j => j.id === blocked.id).status === 'completed');
  assert.equal(state.jobs.find(j => j.id === blocked.id).requiresAuth, false);
  assert.ok(!JSON.stringify(state).includes('DUMMY_TEST_VALUE'));
  const advanced=await request('settings',{cookiesFile:cookieFile,concurrency:1,retries:4,timeout:40,fragmentThreads:2,speedLimitKB:256,proxyUrl:'',resume:false,subLanguages:'pt.*'});assert.equal(advanced.status,200);
  assert.equal((await request('status')).data.concurrency,1);assert.equal((await request('settings',{cookiesFile:cookieFile,concurrency:99})).status,400);
  assert.equal((await request('settings',{cookiesFile:cookieFile,proxyUrl:'file:///bad'})).status,400);
  const outputFile=completed.files[0];assert.equal((await request(`jobs/${completed.id}/remove`,{})).status,200);assert.ok((await fs.stat(outputFile)).isFile());
  assert.ok(!(await request('status')).data.jobs.some(j=>j.id===completed.id));
  const chosen=path.join(root,'destino escolhido');const flat=await request('jobs',{urls:['https://example.com/collision1','https://example.com/collision2'],destination:chosen});
  state=await until(s=>s.jobs.filter(j=>flat.data.ids.includes(j.id)).every(j=>j.status==='completed'));
  const flatJobs=state.jobs.filter(j=>flat.data.ids.includes(j.id));assert.equal(new Set(flatJobs.map(j=>j.files[0])).size,2);for(const j of flatJobs)assert.equal(path.dirname(j.files[0]),chosen);assert.equal((await fs.readdir(chosen,{withFileTypes:true})).filter(e=>e.isDirectory()).length,0);
  await request('clear',{});assert.equal((await request('status')).data.jobs.length,0);assert.ok((await fs.stat(outputFile)).isFile());
  const running = await request('jobs', { urls: ['https://example.com/slow3'] });
  await until(s => s.jobs.find(j => j.id === running.data.ids[0]).status === 'running');
  assert.equal((await request(`jobs/${running.data.ids[0]}/remove`,{})).status,400);await request('clear',{});assert.ok((await request('status')).data.jobs.some(j=>j.id===running.data.ids[0]));
  await app.close();
  const reopened = await createApp({ root, engine, testing: true, noOpen: true });
  assert.equal(reopened.jobs().find(j => j.id === running.data.ids[0]).status, 'interrupted'); await reopened.close();
  assert.equal(JSON.parse(await fs.readFile(path.join(root, 'data', 'auth-settings.json'), 'utf8')).cookiesFile, cookieFile);
});
